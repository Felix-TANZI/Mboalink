const fs = require('fs/promises');
const path = require('path');

const prisma = require('../src/config/prisma');
const { allocateCaptivePortalPort, buildCaptivePortalUrl } = require('../src/modules/hotels/captive-portal-port.service');

const DEFAULT_OUTPUT = path.resolve(__dirname, '../../radius/docker-compose.captive-instances.yml');

function slugify(value) {
  return String(value || 'hotel')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 34) || 'hotel';
}

function yamlQuote(value) {
  return JSON.stringify(String(value ?? ''));
}

async function ensureHotelPorts(hotels) {
  const result = [];

  for (const hotel of hotels) {
    if (hotel.captivePortalPort) {
      result.push(hotel);
      continue;
    }

    const captivePortalPort = await allocateCaptivePortalPort();
    const updated = await prisma.hotel.update({
      where: { id: hotel.id },
      data: { captivePortalPort },
      include: { wifiConfig: { select: { ssid: true } } },
    });
    result.push(updated);
  }

  return result;
}

function renderCompose(hotels) {
  const lines = [
    '# Generated by core_access_and_identity_service_back/scripts/generate-captive-instances.js',
    '# Do not edit manually. Regenerate after creating or disabling a hotel.',
    'services:',
  ];

  for (const hotel of hotels) {
    const suffix = hotel.id.slice(-6).toLowerCase().replace(/[^a-z0-9]/g, '');
    const serviceName = `captive_${slugify(hotel.name)}_${suffix}`;
    const ssid = hotel.wifiConfig?.ssid || '';

    lines.push(
      `  ${serviceName}:`,
      '    build:',
      '      context: .',
      '      dockerfile: Dockerfile',
      '    image: radius-nextjs',
      '    restart: unless-stopped',
      '    depends_on:',
      '      postgres:',
      '        condition: service_healthy',
      '      freeradius:',
      '        condition: service_healthy',
      '    environment:',
      '      POSTGRES_HOST: postgres',
      '      POSTGRES_PORT: 5432',
      '      POSTGRES_DB: radius_hotel',
      '      POSTGRES_USER: postgres',
      '      POSTGRES_PASSWORD: postgres',
      '      RADIUS_HOST: freeradius',
      '      RADIUS_PORT: 1812',
      '      RADIUS_SECRET: testing123',
      '      MBOALINK_API_BASE_URL: ${MBOALINK_API_BASE_URL:-http://13.140.183.51:13000/api/v1}',
      '      MBOALINK_PUBLIC_ASSET_BASE_URL: ${MBOALINK_PUBLIC_ASSET_BASE_URL:-http://13.140.183.51:13000}',
      `      MBOALINK_DEFAULT_HOTEL_ID: ${yamlQuote(hotel.id)}`,
      `      MBOALINK_DEFAULT_SSID: ${yamlQuote(ssid)}`,
      '    ports:',
      `      - "${hotel.captivePortalPort}:3000"`,
      ''
    );
  }

  return `${lines.join('\n')}\n`;
}

async function main() {
  const outputPath = path.resolve(process.env.CAPTIVE_INSTANCES_COMPOSE_PATH || DEFAULT_OUTPUT);
  const hotels = await prisma.hotel.findMany({
    where: { status: 'ACTIVE' },
    include: { wifiConfig: { select: { ssid: true } } },
    orderBy: { createdAt: 'asc' },
  });
  const hotelsWithPorts = await ensureHotelPorts(hotels);
  const compose = renderCompose(hotelsWithPorts);

  await fs.writeFile(outputPath, compose);

  console.log(`Generated ${outputPath}`);
  for (const hotel of hotelsWithPorts) {
    console.log(`${hotel.name} -> ${buildCaptivePortalUrl(hotel.captivePortalPort, {
      hotelId: hotel.id,
      ssid: hotel.wifiConfig?.ssid,
    })}`);
  }
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
