const fs = require('fs/promises');
const path = require('path');

const prisma = require('../src/config/prisma');
const { buildCaptivePortalUrl } = require('../src/modules/hotels/captive-portal-port.service');
const { ensureDefaultCaptivePortal } = require('../src/modules/captive-portal-instances/captive-portal-instance.service');

const DEFAULT_OUTPUT = path.resolve(process.env.CAPTIVE_INSTANCES_COMPOSE_PATH || process.cwd(), 'docker-compose.captive-instances.yml');

function slugify(value) {
  return String(value || 'portal')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 34) || 'portal';
}

function yamlQuote(value) {
  return JSON.stringify(String(value ?? ''));
}

async function ensureActiveHotelsHaveDefaultPortals() {
  const hotels = await prisma.hotel.findMany({
    where: { status: 'ACTIVE' },
    include: { wifiConfig: { select: { ssid: true } } },
    orderBy: { createdAt: 'asc' },
  });

  for (const hotel of hotels) {
    await ensureDefaultCaptivePortal(hotel.id, {
      name: 'Client',
      ssid: hotel.wifiConfig?.ssid,
    });
  }
}

function renderCompose(portals) {
  const lines = [
    '# Generated by core_access_and_identity_service_back/scripts/generate-captive-instances.js',
    '# Do not edit manually. Regenerate after creating/disabling a site portal.',
    'services:',
  ];

  for (const portal of portals) {
    const suffix = portal.id.slice(-6).toLowerCase().replace(/[^a-z0-9]/g, '');
    const serviceName = `captive_${slugify(portal.hotel.name)}_${slugify(portal.name)}_${suffix}`;

    lines.push(
      `  ${serviceName}:`,
      '    build:',
      '      context: .',
      '      dockerfile: Dockerfile',
      '    image: radius-nextjs',
      '    restart: unless-stopped',
      '    depends_on:',
      '      postgres:',
      '        condition: service_healthy',
      '      freeradius:',
      '        condition: service_healthy',
      '    environment:',
      '      POSTGRES_HOST: postgres',
      '      POSTGRES_PORT: 5432',
      '      POSTGRES_DB: radius_hotel',
      '      POSTGRES_USER: postgres',
      '      POSTGRES_PASSWORD: postgres',
      '      RADIUS_HOST: freeradius',
      '      RADIUS_PORT: 1812',
      '      RADIUS_SECRET: testing123',
      '      MBOALINK_API_BASE_URL: ${MBOALINK_API_BASE_URL:-http://13.140.183.51:13000/api/v1}',
      '      MBOALINK_PUBLIC_ASSET_BASE_URL: ${MBOALINK_PUBLIC_ASSET_BASE_URL:-http://13.140.183.51:13000}',
      `      MBOALINK_DEFAULT_PORTAL_ID: ${yamlQuote(portal.id)}`,
      `      MBOALINK_DEFAULT_HOTEL_ID: ${yamlQuote(portal.hotelId)}`,
      `      MBOALINK_DEFAULT_SSID: ${yamlQuote(portal.ssid)}`,
      '    ports:',
      `      - "${portal.port}:3000"`,
      ''
    );
  }

  return `${lines.join('\n')}\n`;
}

async function main() {
  const outputPath = path.resolve(process.env.CAPTIVE_INSTANCES_COMPOSE_PATH || DEFAULT_OUTPUT);

  await ensureActiveHotelsHaveDefaultPortals();

  const portals = await prisma.captivePortalInstance.findMany({
    where: {
      status: 'ACTIVE',
      hotel: { status: 'ACTIVE' },
    },
    include: { hotel: { select: { id: true, name: true } } },
    orderBy: [{ hotel: { name: 'asc' } }, { isDefault: 'desc' }, { createdAt: 'asc' }],
  });

  const compose = renderCompose(portals);
  await fs.writeFile(outputPath, compose);

  console.log(`Generated ${outputPath}`);
  for (const portal of portals) {
    console.log(`${portal.hotel.name} / ${portal.name} (${portal.ssid}) -> ${buildCaptivePortalUrl(portal.port, {
      portalId: portal.id,
      hotelId: portal.hotelId,
      ssid: portal.ssid,
    })}`);
  }
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
